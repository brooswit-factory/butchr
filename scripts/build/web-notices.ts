/**
 * FACTORY-614: `dashboard-app/` now bundles `@launchpad-ui/components`
 * (0.25.0) and `@launchpad-ui/tokens` (0.19.0) into `dist/web/` — both
 * Apache-2.0, which requires the NOTICE/LICENSE text to travel with the
 * bundled code, not just sit in this repo's own devDependency lockfile.
 * `collectThirdPartyNotices` walks the real RUNTIME dependency closure
 * (`package.json`'s `dependencies` field only — `devDependencies` never
 * ship) of those two packages, via Node's own module resolution
 * (`createRequire().resolve`, so a package hoisted anywhere bun's
 * `node_modules` layout put it is still found correctly) rather than
 * inspecting Vite's actual output chunks: tree-shaking can drop some of a
 * dependency's OWN code paths, but it cannot make a package's declared
 * license obligation disappear for the parts that DID ship, so the
 * declared closure is the conservative, defensible boundary — a
 * false-negative here (a used license going unlisted) is the one failure
 * mode this ticket's Apache-2.0 "keep the notice" instruction cares about,
 * and walking the full closure cannot produce one.
 *
 * Pure (no writes) and exported as its own function — unlike
 * `scripts/build/build.ts`, importing this module must not run it (see
 * `scripts/load/inventory.ts`'s `RUNS_ON_IMPORT` — this file is
 * deliberately NOT on that list), so `vite.config.ts`'s own plugin is the
 * only thing that ever calls `collectThirdPartyNotices` and writes its
 * result to disk.
 */
import { createRequire } from "node:module";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";

export interface ThirdPartyPackage {
  name: string;
  version: string;
  license: string;
  licenseText: string;
}

const ROOTS = ["@launchpad-ui/components", "@launchpad-ui/tokens"] as const;
const LICENSE_FILE_CANDIDATES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "NOTICE", "NOTICE.md"];

function findLicenseText(pkgDir: string): string {
  for (const name of LICENSE_FILE_CANDIDATES) {
    const path = join(pkgDir, name);
    if (existsSync(path)) return readFileSync(path, "utf8").trim();
  }
  return "(no LICENSE/NOTICE file found in this package)";
}

/** Walks `name`'s own `dependencies` (never `devDependencies`/`peerDependencies` — those don't ship) transitively, resolved relative to `fromDir` so hoisted layouts resolve exactly like Node/bun would at runtime. */
function walk(name: string, fromDir: string, resolve: (specifier: string, fromDir: string) => string, seen: Map<string, ThirdPartyPackage>): void {
  if (seen.has(name)) return;
  const pkgJsonPath = resolve(`${name}/package.json`, fromDir);
  const dir = dirname(pkgJsonPath);
  const pkg = JSON.parse(readFileSync(pkgJsonPath, "utf8")) as { version: string; license?: string; dependencies?: Record<string, string> };
  seen.set(name, { name, version: pkg.version, license: pkg.license ?? "UNKNOWN", licenseText: findLicenseText(dir) });
  for (const dep of Object.keys(pkg.dependencies ?? {})) walk(dep, dir, resolve, seen);
}

export function collectThirdPartyPackages(repoRoot: string): ThirdPartyPackage[] {
  const require = createRequire(join(repoRoot, "package.json"));
  const resolve = (specifier: string, fromDir: string) => require.resolve(specifier, { paths: [fromDir] });
  const seen = new Map<string, ThirdPartyPackage>();
  for (const root of ROOTS) walk(root, repoRoot, resolve, seen);
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

export function renderThirdPartyNotices(packages: readonly ThirdPartyPackage[]): string {
  const header =
    "Third-party notices\n" +
    "====================\n" +
    "This bundle includes code from the following packages, pulled in via\n" +
    "@launchpad-ui/components and @launchpad-ui/tokens (the LaunchPad design\n" +
    "system). Generated by scripts/build/web-notices.ts — see that file for\n" +
    "exactly how this list is computed.\n\n";
  const entries = packages.map((p) => `--------------------------------------------------------------------\n${p.name}@${p.version} (${p.license})\n--------------------------------------------------------------------\n${p.licenseText}\n`);
  return header + entries.join("\n");
}

export function collectThirdPartyNotices(repoRoot: string): string {
  return renderThirdPartyNotices(collectThirdPartyPackages(repoRoot));
}
